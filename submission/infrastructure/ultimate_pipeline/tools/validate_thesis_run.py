def validate_optional_generalization_and_repro(run_root: Path, strict_mode: bool):
    """Validate optional generalization/repro artifacts when present."""

    gen_csv = run_root / "generalization_results.csv"
    gen_json = run_root / "generalization_results.json"
    gen_curve = run_root / "gen_many_curve.csv"
    gen_ci = run_root / "generalization_bootstrap_ci.json"
    real_u_report = run_root / "real_u_eval_report.json"
    any_gen = any(p.is_file() for p in (gen_csv, gen_json, gen_curve, gen_ci))
    if any_gen:
        for req in (gen_csv, gen_json, gen_curve, gen_ci, real_u_report):
            if not req.is_file():
                fail_validation("Missing generalization artifact", req)

        try:
            with open(gen_csv, "r", encoding="utf-8", newline="") as f:
                reader = csv.DictReader(f)
                cols = set(reader.fieldnames or [])
            new_required = {
                "condition",
                "K",
                "train_dataset_count",
                "sim_mIoU",
                "sim_pixel_accuracy",
                "real_u_entropy_mean",
                "real_u_confidence_mean",
                "real_u_ece",
                "checkpoint",
                "train_dataset_roots",
            }
            legacy_required = {
                "K",
                "test_target",
                "mean_entropy",
                "std_entropy",
                "p10_entropy",
                "p90_entropy",
                "ece",
                "delta_vs_manual_baseline_mean_entropy",
                "delta_vs_manual_baseline_ece",
            }
            if not (new_required.issubset(cols) or legacy_required.issubset(cols)):
                fail_validation("generalization_results.csv does not match supported schema", gen_csv)
        except Exception as exc:
            fail_validation(f"Failed to validate generalization_results.csv: {exc}", gen_csv)

        try:
            gj = json.loads(gen_json.read_text(encoding="utf-8", errors="replace"))
            if not isinstance(gj, dict):
                fail_validation("generalization_results.json must be an object", gen_json)
            else:
                if gj.get("placeholder") is True:
                    fail_validation("generalization_results.json is marked as placeholder", gen_json)
                rows = gj.get("rows")
                if not isinstance(rows, list) or not rows:
                    fail_validation("generalization_results.json missing non-empty rows", gen_json)
                elif any(isinstance(r, dict) and "test_target" in r for r in rows):
                    fail_validation("generalization_results.json appears to use placeholder/legacy rows", gen_json)
                conditioned_top = gj.get("real_u_conditioned_on_k")
                row_conditioned = [
                    r.get("real_u_conditioned_on_k")
                    for r in rows
                    if isinstance(r, dict) and "real_u_conditioned_on_k" in r
                ]
                if strict_mode and not isinstance(conditioned_top, bool):
                    fail_validation("generalization_results.json missing boolean real_u_conditioned_on_k in strict mode", gen_json)
                if strict_mode and not row_conditioned:
                    fail_validation("generalization_results.json rows missing real_u_conditioned_on_k in strict mode", gen_json)
        except Exception as exc:
            fail_validation(f"Failed to validate generalization_results.json: {exc}", gen_json)

        try:
            with open(gen_curve, "r", encoding="utf-8", newline="") as f:
                reader = csv.DictReader(f)
                cols = set(reader.fieldnames or [])
            if not {"K"}.issubset(cols):
                fail_validation("gen_many_curve.csv missing K column", gen_curve)
        except Exception as exc:
            fail_validation(f"Failed to validate gen_many_curve.csv: {exc}", gen_curve)

        try:
            ci_obj = json.loads(gen_ci.read_text(encoding="utf-8", errors="replace"))
            if not isinstance(ci_obj, dict):
                fail_validation("generalization_bootstrap_ci.json must be an object", gen_ci)
            elif not isinstance(ci_obj.get("rows"), list):
                fail_validation("generalization_bootstrap_ci.json missing rows list", gen_ci)
        except Exception as exc:
            fail_validation(f"Failed to validate generalization_bootstrap_ci.json: {exc}", gen_ci)

        try:
            data = json.loads(real_u_report.read_text(encoding="utf-8", errors="replace"))
            real = data.get("real", {}) if isinstance(data, dict) else {}
            if not isinstance(real, dict):
                fail_validation("Invalid Real_U report schema: missing real block", real_u_report)
            else:
                required = (
                    "entropy_mean",
                    "entropy_std",
                    "entropy_p10",
                    "entropy_p90",
                    "confidence_mean",
                    "confidence_std",
                    "confidence_p10",
                    "confidence_p90",
                    "ece",
                    "entropy_values",
                    "confidence_values",
                    "ece_values",
                )
                for key in required:
                    if key not in real:
                        fail_validation(f"Real_U report missing key {key}", real_u_report)
                if not isinstance(real.get("entropy_values"), list):
                    fail_validation("Real_U report entropy_values must be a list", real_u_report)
                if not isinstance(real.get("confidence_values"), list):
                    fail_validation("Real_U report confidence_values must be a list", real_u_report)
                if not isinstance(real.get("ece_values"), list):
                    fail_validation("Real_U report ece_values must be a list", real_u_report)
                conditioned_real = data.get("real_u_conditioned_on_k") if isinstance(data, dict) else None
                if strict_mode and not isinstance(conditioned_real, bool):
                    fail_validation("real_u_eval_report.json missing boolean real_u_conditioned_on_k in strict mode", real_u_report)
                try:
                    gj = json.loads(gen_json.read_text(encoding="utf-8", errors="replace"))
                    conditioned_top = gj.get("real_u_conditioned_on_k") if isinstance(gj, dict) else None
                except Exception:
                    conditioned_top = None
                if isinstance(conditioned_top, bool) and isinstance(conditioned_real, bool) and conditioned_real != conditioned_top:
                    fail_validation(
                        "Mismatch for real_u_conditioned_on_k between generalization_results.json and real_u_eval_report.json",
                        real_u_report,
                    )
        except Exception as exc:
            fail_validation(f"Failed to validate Real_U report: {exc}", real_u_report)

    env_snapshot = run_root / "environment_snapshot.json"
    if env_snapshot.is_file():
        try:
            env = json.loads(env_snapshot.read_text(encoding="utf-8", errors="replace"))
            for key in ("python_version", "platform", "pip_freeze_sha256"):
                if key not in env:
                    fail_validation(f"environment_snapshot.json missing key: {key}", env_snapshot)
        except Exception as exc:
            fail_validation(f"Failed to validate environment_snapshot.json: {exc}", env_snapshot)

    # If determinism_report.json exists, determinism_delta.csv must exist beside it.
    for rep in run_root.rglob("determinism_report.json"):
        delta = rep.parent / "determinism_delta.csv"
        if not delta.is_file():
            fail_validation("determinism_delta.csv required when determinism_report.json exists", delta)

    # Also enforce root-level determinism delta when root-level report exists.
    root_det_report = run_root / "determinism_report.json"
    if root_det_report.is_file():
        root_delta = run_root / "determinism_delta.csv"
        if not root_delta.is_file():
            fail_validation("Missing determinism_delta.csv", root_delta)

    # Require settings_fingerprint in pipeline report bundle (when report exists).
    report_candidates = [
        run_root / "logs" / "pipeline_report.json",
        run_root / "logs" / "validation_report_full.json",
    ]
    report_found = False
    found_fingerprint = False
    for report_path in report_candidates:
        if not report_path.is_file():
            continue
        report_found = True
        try:
            data = json.loads(report_path.read_text(encoding="utf-8", errors="replace"))
            diagnostics = data.get("diagnostics", {}) if isinstance(data, dict) else {}
            details = diagnostics.get("details", {}) if isinstance(diagnostics, dict) else {}
            fp_obj = details.get("settings_fingerprint", {}) if isinstance(details, dict) else {}
            fp = fp_obj.get("sha256") if isinstance(fp_obj, dict) else None
            if isinstance(fp, str) and fp:
                found_fingerprint = True
                break
        except Exception:
            continue
    if report_found and not found_fingerprint:
        fail_validation("Missing settings_fingerprint in pipeline report bundle")

    # Root-level pipeline_report.json support (legacy layouts)
    root_report = run_root / "pipeline_report.json"
    if root_report.is_file():
        try:
            data = json.loads(root_report.read_text(encoding="utf-8", errors="replace"))
            has_fp = False
            if isinstance(data, dict):
                if "settings_fingerprint" in data:
                    has_fp = True
                diagnostics = data.get("diagnostics", {}) if isinstance(data.get("diagnostics"), dict) else {}
                details = diagnostics.get("details", {}) if isinstance(diagnostics, dict) else {}
                if isinstance(details, dict) and "settings_fingerprint" in details:
                    has_fp = True
            if not has_fp:
                fail_validation("Missing settings_fingerprint in pipeline_report.json", root_report)
        except Exception as exc:
            fail_validation(f"Failed to validate pipeline_report.json: {exc}", root_report)

    # OSM archive requirement when run summary declares an OSM input
    run_summary = run_root / "run_summary.json"
    if run_summary.is_file():
        try:
            summary = json.loads(run_summary.read_text(encoding="utf-8", errors="replace"))
            osm_file = ""
            if isinstance(summary, dict):
                inputs = summary.get("inputs", {})
                if isinstance(inputs, dict):
                    osm_file = str(inputs.get("osm_file") or "")
            if osm_file:
                archive = run_root / "osm_archive.json"
                if not archive.is_file():
                    fail_validation("Missing osm_archive.json while OSM_FILE is declared", archive)
                else:
                    arc = json.loads(archive.read_text(encoding="utf-8", errors="replace"))
                    md5 = arc.get("osm_md5") if isinstance(arc, dict) else None
                    if not isinstance(md5, str) or not md5:
                        fail_validation("osm_archive.json missing osm_md5", archive)
                    bbox = _extract_bbox_values(arc)
                    if bbox is None:
                        inputs = summary.get("inputs", {}) if isinstance(summary, dict) else {}
                        bbox = _extract_bbox_values(inputs)
                    if bbox is None:
                        fail_validation("Missing bbox in osm_archive.json or run_summary inputs", archive)
                    else:
                        for k, v in CANONICAL_BBOX.items():
                            if abs(float(bbox.get(k, 0.0)) - float(v)) > 1e-12:
                                fail_validation(f"BBox mismatch for {k}: expected {v}, got {bbox.get(k)}", archive)
        except Exception as exc:
            fail_validation(f"Failed to validate OSM archive contract: {exc}", run_summary)

    # DEM/elevation contract (only if DEM stage details are present).
    if report_found:
        for report_path in report_candidates:
            if not report_path.is_file():
                continue
            try:
                data = json.loads(report_path.read_text(encoding="utf-8", errors="replace"))
                diagnostics = data.get("diagnostics", {}) if isinstance(data, dict) else {}
                details = diagnostics.get("details", {}) if isinstance(diagnostics, dict) else {}
                if not isinstance(details, dict):
                    continue
                dem_diag = details.get("dem_diagnostics")
                if not isinstance(dem_diag, dict):
                    continue
                dem_exists = dem_diag.get("exists")
                elev_stats = details.get("elevation_stats")
                if dem_exists is True:
                    if not isinstance(elev_stats, dict):
                        fail_validation("DEM enabled but elevation_stats missing", report_path)
                    else:
                        for key in ("mean", "stddev", "count"):
                            if key not in elev_stats:
                                fail_validation(f"elevation_stats missing key: {key}", report_path)
                elif dem_exists is False:
                    dem_disabled = False
                    if isinstance(elev_stats, dict) and elev_stats.get("DEM_disabled") is True:
                        dem_disabled = True
                    if details.get("DEM_disabled") is True:
                        dem_disabled = True
                    if not dem_disabled:
                        fail_validation("DEM disabled but DEM_disabled not recorded explicitly", report_path)
            except Exception as exc:
                fail_validation(f"Failed to validate DEM/elevation contract: {exc}", report_path)

    # If Real_U report exists independently, require core keys.
    if real_u_report.is_file() and not any_gen:
        try:
            data = json.loads(real_u_report.read_text(encoding="utf-8", errors="replace"))
            real = data.get("real", {}) if isinstance(data, dict) else {}
            if not isinstance(real, dict):
                fail_validation("Invalid Real_U report schema: missing real block", real_u_report)
            elif "entropy_mean" not in real or "confidence_mean" not in real:
                fail_validation("Real_U report missing keys entropy_mean/confidence_mean", real_u_report)
        except Exception as exc:
            fail_validation(f"Failed to validate Real_U report: {exc}", real_u_report)


def main():
    parser = argparse.ArgumentParser(description="Validate a CARLA thesis run for QA and reproducibility.")
    parser.add_argument("run_root", type=str, help="Path to the root directory of the thesis run.")
    parser.add_argument("--strict", action="store_true", help="Enable thesis_final strict validation gates.")
    args = parser.parse_args()

    run_root_path = Path(args.run_root).resolve()
    if not run_root_path.is_dir():
        fail_validation("The provided run root is not a valid directory", run_root_path)
        print("\n".join(_VALIDATION_ERRORS), file=sys.stderr)
        sys.exit(1)

    print(f"Starting validation for run root: {run_root_path}")
    strict_mode = bool(args.strict)

    validate_agent_sync_contract()
    validate_bbox_contract(run_root_path, strict_mode)
    if _is_bounded_scenario_b_layout(run_root_path):
        validate_bounded_scenario_b_evidence(run_root_path, strict_mode)
    else:
        validate_determinism_audit(run_root_path)
        validate_comparison_folders(run_root_path, strict_mode)
        validate_perception_evidence_packs(run_root_path, strict_mode)
        validate_xodr_link_integrity(run_root_path, required=True)
    validate_optional_generalization_and_repro(run_root_path, strict_mode)

    if _VALIDATION_ERRORS:
        print("\n".join(_VALIDATION_ERRORS), file=sys.stderr)
        sys.exit(1)

    print("\nAll thesis run validations passed successfully!")
    sys.exit(0)

if __name__ == "__main__":
    main()
