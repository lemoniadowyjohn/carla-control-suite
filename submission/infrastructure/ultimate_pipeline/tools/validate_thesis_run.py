def _validate_domain_gap_bundle(domain_gap_path: Path, strict_mode: bool, *, require_coordinate_system: bool) -> None:
    expected_files = [
        FULL_REPORT_JSON,
        SUMMARY_CSV,
        REPRODUCIBILITY_HASH_JSON,
        TILE_PAIRING_REPORT_JSON,
        DOMAIN_GAP_STATUS_JSON,
    ]
    if require_coordinate_system:
        expected_files.append(COORDINATE_SYSTEM_JSON)
    for file_name in expected_files:
        file_path = domain_gap_path / file_name
        if not file_path.is_file():
            fail_validation("Missing required file in comparison domain_gap", file_path)

    pairing_report_path = domain_gap_path / TILE_PAIRING_REPORT_JSON
    try:
        with open(pairing_report_path, "r", encoding="utf-8") as f:
            pairing_data = json.load(f)
        if not isinstance(pairing_data, dict):
            fail_validation(f"{TILE_PAIRING_REPORT_JSON} root must be an object", pairing_report_path)
        else:
            has_legacy_schema = "pairing_method" in pairing_data
            has_current_schema = "algorithm" in pairing_data and "matches" in pairing_data
            if has_legacy_schema:
                pairing_method = pairing_data.get("pairing_method")
                one_to_one_ok = pairing_data.get("one_to_one", {}).get("ok")
                dup_manual = pairing_data.get("one_to_one", {}).get("duplicate_manual")
                dup_auto = pairing_data.get("one_to_one", {}).get("duplicate_auto")
                if pairing_method not in ["hungarian", "greedy"]:
                    fail_validation(f"Invalid 'pairing_method' in {TILE_PAIRING_REPORT_JSON}: {pairing_method}", pairing_report_path)
                if one_to_one_ok is not True:
                    fail_validation(
                        f"Expected 'one_to_one.ok' to be True in {TILE_PAIRING_REPORT_JSON}, but got {one_to_one_ok} "
                        f"(duplicate_manual={dup_manual}, duplicate_auto={dup_auto})",
                        pairing_report_path,
                    )
                if "num_pairs" not in pairing_data:
                    fail_validation(f"Missing 'num_pairs' in {TILE_PAIRING_REPORT_JSON}", pairing_report_path)
                if "pairs" not in pairing_data or not isinstance(pairing_data.get("pairs"), list):
                    fail_validation(f"Missing 'pairs' list in {TILE_PAIRING_REPORT_JSON}", pairing_report_path)
            elif has_current_schema:
                matches = pairing_data.get("matches")
                summary = pairing_data.get("summary")
                if not isinstance(matches, dict):
                    fail_validation(f"{TILE_PAIRING_REPORT_JSON} current schema requires dict 'matches'", pairing_report_path)
                if not isinstance(summary, dict):
                    fail_validation(f"{TILE_PAIRING_REPORT_JSON} current schema requires object 'summary'", pairing_report_path)
                if isinstance(matches, dict) and not matches:
                    fail_validation(f"{TILE_PAIRING_REPORT_JSON} current schema has empty matches", pairing_report_path)
            else:
                fail_validation(
                    f"{TILE_PAIRING_REPORT_JSON} schema unsupported (expected legacy pairing_method or current algorithm/matches)",
                    pairing_report_path,
                )
    except json.JSONDecodeError:
        fail_validation(f"Invalid JSON in {TILE_PAIRING_REPORT_JSON}", pairing_report_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {TILE_PAIRING_REPORT_JSON}: {exc}", pairing_report_path)

    full_report_path = domain_gap_path / FULL_REPORT_JSON
    try:
        with open(full_report_path, "r", encoding="utf-8") as f:
            full_report = json.load(f)
        if not isinstance(full_report, dict):
            fail_validation("full_report.json must be an object", full_report_path)
        else:
            domain_gap = full_report.get("domain_gap")
            structural_gap = full_report.get("structural_domain_gap")
            if isinstance(domain_gap, dict):
                for key in sorted(REQUIRED_DOMAIN_GAP_METRICS):
                    if key not in domain_gap:
                        fail_validation(f"full_report.json domain_gap missing metric '{key}'", full_report_path)
                    else:
                        try:
                            float(domain_gap.get(key))
                        except Exception:
                            fail_validation(f"full_report.json domain_gap metric '{key}' must be numeric", full_report_path)
            elif isinstance(structural_gap, dict):
                for key in ("geometry", "intersection", "curvature"):
                    if key not in structural_gap:
                        fail_validation(f"full_report.json structural_domain_gap missing '{key}'", full_report_path)
            else:
                fail_validation(
                    "full_report.json missing supported gap object (domain_gap or structural_domain_gap)",
                    full_report_path,
                )
    except json.JSONDecodeError:
        fail_validation(f"Invalid JSON in {FULL_REPORT_JSON}", full_report_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {FULL_REPORT_JSON}: {exc}", full_report_path)

    summary_path = domain_gap_path / SUMMARY_CSV
    try:
        with open(summary_path, "r", encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
            cols = [c or "" for c in (reader.fieldnames or [])]
        metric_col = "metric" if "metric" in cols else (cols[0] if cols else "")
        found_metrics = set()
        for row in rows:
            if not isinstance(row, dict):
                continue
            metric_name = str(row.get(metric_col, "")).strip() if metric_col else ""
            if metric_name:
                found_metrics.add(metric_name)
        supports_legacy = REQUIRED_DOMAIN_GAP_METRICS.issubset(found_metrics)
        supports_current = bool(CURRENT_SUMMARY_METRICS.intersection(found_metrics))
        if not (supports_legacy or supports_current):
            fail_validation(
                f"summary.csv missing supported metric set (legacy={sorted(REQUIRED_DOMAIN_GAP_METRICS)}, "
                f"current_any={sorted(CURRENT_SUMMARY_METRICS)})",
                summary_path,
            )
        if strict_mode and len(found_metrics) < 5:
            fail_validation("summary.csv appears smoke-only (<5 metrics rows) in strict mode", summary_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {SUMMARY_CSV}: {exc}", summary_path)

    status_path = domain_gap_path / DOMAIN_GAP_STATUS_JSON
    try:
        with open(status_path, "r", encoding="utf-8") as f:
            status_data = json.load(f)
        if not isinstance(status_data, dict):
            fail_validation(f"{DOMAIN_GAP_STATUS_JSON} root must be an object", status_path)
        else:
            if "success" in status_data:
                if bool(status_data.get("success")) is not True:
                    fail_validation(f"{DOMAIN_GAP_STATUS_JSON} indicates failure", status_path)
                if strict_mode and str(status_data.get("status", "")).lower() in {"fail", "failed"}:
                    fail_validation(f"{DOMAIN_GAP_STATUS_JSON} status must not be failed in strict mode", status_path)
            else:
                status_token = str(status_data.get("status", "")).strip().lower()
                if status_token and status_token in {"failed", "fail", "error"}:
                    fail_validation(f"{DOMAIN_GAP_STATUS_JSON} indicates failure", status_path)
                if "metrics" not in status_data and "composite_gap" not in status_data:
                    fail_validation(
                        f"{DOMAIN_GAP_STATUS_JSON} missing supported status keys (success or metrics/composite_gap)",
                        status_path,
                    )
    except json.JSONDecodeError:
        fail_validation(f"Invalid JSON in {DOMAIN_GAP_STATUS_JSON}", status_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {DOMAIN_GAP_STATUS_JSON}: {exc}", status_path)

    coordinate_path = domain_gap_path / COORDINATE_SYSTEM_JSON
    if coordinate_path.is_file():
        try:
            with open(coordinate_path, "r", encoding="utf-8") as f:
                coordinate_data = json.load(f)
            if "units" not in coordinate_data:
                fail_validation(f"Missing 'units' in {COORDINATE_SYSTEM_JSON}", coordinate_path)
            if "osm_bbox_wgs84" not in coordinate_data:
                fail_validation(f"Missing 'osm_bbox_wgs84' in {COORDINATE_SYSTEM_JSON}", coordinate_path)
        except json.JSONDecodeError:
            fail_validation(f"Invalid JSON in {COORDINATE_SYSTEM_JSON}", coordinate_path)
        except Exception as exc:
            fail_validation(f"Failed to validate {COORDINATE_SYSTEM_JSON}: {exc}", coordinate_path)
    elif require_coordinate_system:
        fail_validation("Missing required coordinate_system.json in legacy domain gap layout", coordinate_path)


def validate_comparison_folders(run_root: Path, strict_mode: bool):
    """
    Validates comparison folders in legacy and split layouts.
    """
    thesis_final_path = run_root / "thesis_final"
    if thesis_final_path.is_dir():
        comparison_runs = [d for d in thesis_final_path.iterdir() if d.is_dir()]
        if not comparison_runs:
            fail_validation("No comparison run folders found under thesis_final", thesis_final_path)
            return

        for comp_run_path in comparison_runs:
            print(f"Validating comparison run: {comp_run_path}")
            domain_gap_path = comp_run_path / "domain_gap"
            if not domain_gap_path.is_dir():
                fail_validation("Missing 'domain_gap' folder in comparison run", domain_gap_path)
                continue
            _validate_domain_gap_bundle(
                domain_gap_path, strict_mode, require_coordinate_system=True
            )
        print("Comparison folders validation successful.")
        return

    split_candidates = [
        run_root / "thesis_results" / "structural_gap_v1",
        run_root / "structural_gap_v1",
    ]
    split_root = next((p for p in split_candidates if p.is_dir()), None)
    if split_root is None:
        fail_validation(
            "No supported comparison layout found (expected thesis_final or thesis_results/structural_gap_v1)",
            run_root,
        )
        return

    comparison_runs = [d for d in split_root.iterdir() if d.is_dir()]
    if not comparison_runs:
        fail_validation("No comparison run folders found under structural_gap_v1", split_root)
        return

    for comp_run_path in comparison_runs:
        print(f"Validating comparison run: {comp_run_path}")
        domain_gap_path = comp_run_path / "domain_gap"
        if domain_gap_path.is_dir():
            _validate_domain_gap_bundle(
                domain_gap_path, strict_mode, require_coordinate_system=False
            )
        else:
            # Current structural-gap layout stores required files at run-root.
            _validate_domain_gap_bundle(
                comp_run_path, strict_mode, require_coordinate_system=False
            )
    print("Comparison folders validation successful.")


def _validate_perception_pack(
    pack_path: Path,
    pack_name: str,
    strict_mode: bool,
    *,
    require_scene_readiness: bool = True,
) -> None:
    if not pack_path.is_dir():
        fail_validation(f"Perception evidence pack '{pack_name}' not found", pack_path)
        return

    scene_readiness_path = pack_path / SCENE_READINESS_REPORT_JSON
    if not scene_readiness_path.is_file():
        if require_scene_readiness:
            fail_validation(
                f"Missing required file in perception evidence pack '{pack_name}'",
                scene_readiness_path,
            )
    else:
        try:
            with open(scene_readiness_path, "r", encoding="utf-8") as f:
                scene_readiness = json.load(f)
            if not isinstance(scene_readiness, dict):
                fail_validation(
                    f"Invalid JSON object in {SCENE_READINESS_REPORT_JSON}",
                    scene_readiness_path,
                )
            else:
                required_scene_keys = [
                    "timestamp",
                    "thesis_rig_attached",
                    "enrichments_file_found",
                    "missing_required_types",
                    "qa_bundle_written",
                    "safe_to_start_recording",
                ]
                for key in required_scene_keys:
                    if key not in scene_readiness:
                        fail_validation(
                            f"{SCENE_READINESS_REPORT_JSON} missing key: {key}",
                            scene_readiness_path,
                        )
                if not isinstance(scene_readiness.get("timestamp"), str):
                    fail_validation(
                        f"{SCENE_READINESS_REPORT_JSON} timestamp must be a string",
                        scene_readiness_path,
                    )
                for bool_key in (
                    "thesis_rig_attached",
                    "enrichments_file_found",
                    "qa_bundle_written",
                    "safe_to_start_recording",
                ):
                    if bool_key in scene_readiness and not isinstance(
                        scene_readiness.get(bool_key), bool
                    ):
                        fail_validation(
                            f"{SCENE_READINESS_REPORT_JSON} field '{bool_key}' must be boolean",
                            scene_readiness_path,
                        )

                missing_required_types = scene_readiness.get("missing_required_types")
                if not isinstance(missing_required_types, list):
                    fail_validation(
                        f"{SCENE_READINESS_REPORT_JSON} missing_required_types must be a list",
                        scene_readiness_path,
                    )
                elif len(missing_required_types) > 0:
                    fail_validation(
                        f"{SCENE_READINESS_REPORT_JSON} missing_required_types must be empty",
                        scene_readiness_path,
                    )

                if scene_readiness.get("safe_to_start_recording") is not True:
                    fail_validation(
                        f"{SCENE_READINESS_REPORT_JSON} must set safe_to_start_recording=true",
                        scene_readiness_path,
                    )
        except json.JSONDecodeError:
            fail_validation(f"Invalid JSON in {SCENE_READINESS_REPORT_JSON}", scene_readiness_path)
        except Exception as exc:
            fail_validation(
                f"Failed to validate {SCENE_READINESS_REPORT_JSON}: {exc}",
                scene_readiness_path,
            )

    expected_files = [
        PERCEPTION_STATUS_JSON,
        RIG_VERIFICATION_JSON,
        EGO_SPAWN_PNG,
        CAMERA_FRONT_PNG,
        LIDAR_BEV_PNG,
    ]
    for file_name in expected_files:
        file_path = pack_path / file_name
        if not file_path.is_file():
            fail_validation(f"Missing required file in perception evidence pack '{pack_name}'", file_path)

    strict_requested_for_pack = bool(strict_mode)
    require_overlay = bool(strict_mode)
    require_objects = bool(strict_mode)
    require_evidence_pack = bool(strict_mode)
    perception_status_path = pack_path / PERCEPTION_STATUS_JSON
    if perception_status_path.is_file():
        try:
            with open(perception_status_path, "r", encoding="utf-8") as f:
                ps = json.load(f)
            required = ps.get("required_artifacts", {}) if isinstance(ps, dict) else {}
            if isinstance(required, dict):
                require_overlay = bool(require_overlay or required.get("require_overlay"))
                require_objects = bool(require_objects or required.get("require_objects"))
                require_evidence_pack = bool(require_evidence_pack or required.get("require_evidence_pack"))
                strict_requested_for_pack = bool(
                    strict_requested_for_pack
                    or require_overlay
                    or require_objects
                    or require_evidence_pack
                )
            if strict_requested_for_pack and not isinstance(required, dict):
                fail_validation("perception_status.json missing required_artifacts block in strict mode", perception_status_path)
        except Exception:
            pass

    if require_overlay:
        strict_path = pack_path / LIDAR_OVERLAY_PNG
        if not strict_path.is_file():
            fail_validation(f"Missing strict perception artifact '{LIDAR_OVERLAY_PNG}'", strict_path)
    if require_objects:
        for strict_file in (OBJECTS_PLACED_JSON, OBJECTS_PLACED_PNG):
            strict_path = pack_path / strict_file
            if not strict_path.is_file():
                fail_validation(f"Missing strict perception artifact '{strict_file}'", strict_path)

    rig_verification_path = pack_path / RIG_VERIFICATION_JSON
    try:
        with open(rig_verification_path, "r", encoding="utf-8") as f:
            rig_data = json.load(f)
        if not _validate_rig_contract_schema(rig_data, rig_verification_path):
            return
        use_k_undist = _rig_bool(rig_data, "use_K_undistortion_only")
        ignored_kd = _rig_bool(rig_data, "ignored_K_and_D")
        ctv_inverted = _rig_bool(rig_data, "ctv_inverted")
        vtl_inverted = _rig_bool(rig_data, "vtl_inverted")
        compliance = rig_data.get("thesis_compliance", {})
        if isinstance(compliance, dict):
            if (
                compliance.get("use_K_undistortion_only") != use_k_undist
                or compliance.get("ignored_K_and_D") != ignored_kd
                or compliance.get("ctv_inverted") != ctv_inverted
                or compliance.get("vtl_inverted") != vtl_inverted
            ):
                fail_validation(
                    "Top-level rig verification values must match thesis_compliance block",
                    rig_verification_path,
                )

        if use_k_undist is not True:
            fail_validation(
                f"Expected 'use_K_undistortion_only' to be True in {RIG_VERIFICATION_JSON}, but got {use_k_undist}",
                rig_verification_path,
            )
        if ignored_kd is not True:
            fail_validation(
                f"Expected 'ignored_K_and_D' to be True in {RIG_VERIFICATION_JSON}, but got {ignored_kd}",
                rig_verification_path,
            )
        if ctv_inverted is not False:
            fail_validation(f"Expected 'ctv_inverted' to be False in {RIG_VERIFICATION_JSON}, but got {ctv_inverted}", rig_verification_path)
        if vtl_inverted is not True:
            fail_validation(f"Expected 'vtl_inverted' to be True in {RIG_VERIFICATION_JSON}, but got {vtl_inverted}", rig_verification_path)
    except json.JSONDecodeError:
        fail_validation(f"Invalid JSON in {RIG_VERIFICATION_JSON}", rig_verification_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {RIG_VERIFICATION_JSON}: {exc}", rig_verification_path)

    try:
        with open(perception_status_path, "r", encoding="utf-8") as f:
            ps = json.load(f)
        env = ps.get("environment", {}) if isinstance(ps, dict) else {}
        if not isinstance(env, dict):
            fail_validation("perception_status.json missing 'environment' object", perception_status_path)
        else:
            for key in ("weather", "traffic_manager_seed", "ego_spawn_transform"):
                if key not in env:
                    fail_validation(f"perception_status.json environment missing key: {key}", perception_status_path)
            if strict_requested_for_pack:
                required_artifacts = ps.get("required_artifacts")
                produced_artifacts = ps.get("produced_artifacts")
                if not isinstance(required_artifacts, dict):
                    fail_validation("perception_status.json required_artifacts missing in strict mode", perception_status_path)
                if not isinstance(produced_artifacts, dict):
                    fail_validation("perception_status.json produced_artifacts missing in strict mode", perception_status_path)
    except json.JSONDecodeError:
        fail_validation(f"Invalid JSON in {PERCEPTION_STATUS_JSON}", perception_status_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {PERCEPTION_STATUS_JSON}: {exc}", perception_status_path)


