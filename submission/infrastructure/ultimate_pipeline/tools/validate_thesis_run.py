_VALIDATION_ERRORS = []

def fail_validation(message, path=None):
    """Record a failure (do not exit immediately)."""
    if path:
        _VALIDATION_ERRORS.append(f"ERROR: {message} at: {path}")
    else:
        _VALIDATION_ERRORS.append(f"ERROR: {message}")


