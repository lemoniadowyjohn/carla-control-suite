def validate_xodr_link_integrity(run_root: Path, *, required: bool = True):
    """Validate junction-link integrity gate report."""
    report_path = run_root / XODR_LINK_INTEGRITY_JSON
    if not report_path.is_file():
        if required:
            fail_validation("Missing required xodr link integrity report", report_path)
        else:
            print(f"Skipping optional xodr link integrity check (not found): {report_path}")
        return

    patch_report_path = run_root / JUNCTION_LINK_PATCH_REPORT_JSON
    if not patch_report_path.is_file():
        fail_validation("Missing required junction link patch report", patch_report_path)

    try:
        with open(report_path, "r", encoding="utf-8") as f:
            report_data = json.load(f)
        required_keys = [
            "roads_total",
            "junctions_total",
            "added_junction_links",
            "missing_road_to_junction_links_before",
            "missing_road_to_junction_links_after",
            "remaining_unlinked_nonjunction_roads",
            "suspicious_matches",
            "notes",
            "output_xodr_path",
            "input_xodr_sha256",
            "output_xodr_sha256",
        ]
        for key in required_keys:
            if key not in report_data:
                fail_validation(f"Missing '{key}' in {XODR_LINK_INTEGRITY_JSON}", report_path)

        remaining = report_data.get("missing_road_to_junction_links_after")
        if remaining != 0:
            fail_validation(
                f"Expected 'missing_road_to_junction_links_after' to be 0 in {XODR_LINK_INTEGRITY_JSON}, but got {remaining}",
                report_path,
            )
    except json.JSONDecodeError:
        fail_validation(f"Invalid JSON in {XODR_LINK_INTEGRITY_JSON}", report_path)
    except Exception as exc:
        fail_validation(f"Failed to validate {XODR_LINK_INTEGRITY_JSON}: {exc}", report_path)


