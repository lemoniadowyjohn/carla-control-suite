def utc_stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def _sha(obj: Any) -> str:
    import hashlib

    return hashlib.sha256(
        json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("utf-8")
    ).hexdigest()


def git(*args: str) -> str:
    try:
        out = subprocess.run(
            ["git", *args], capture_output=True, text=True, timeout=10.0
        )
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:
        return ""


def rpc_probe(host: str, ports: List[int], timeout: float = 1.5) -> Dict[str, Any]:
    results = {}
    for port in ports:
        sock = socket.socket()
        sock.settimeout(timeout)
        try:
            sock.connect((host, port))
            results[str(port)] = "OPEN"
        except Exception as exc:
            results[str(port)] = f"CLOSED:{type(exc).__name__}"
        finally:
            sock.close()
    reachable = any(v == "OPEN" for v in results.values())
    return {"host": host, "ports": results, "reachable": reachable}


def carla_api_version() -> Dict[str, Any]:
    try:
        import carla  # type: ignore

        wp = getattr(carla, "WeatherParameters", None)
        fields = (
            sorted(a for a in dir(wp) if not a.startswith("_") and a.islower())
            if wp is not None
            else []
        )
        presets = sorted(a for a in dir(wp) if a[:1].isupper()) if wp is not None else []
        return {
            "available": True,
            "declared_version": str(getattr(carla, "__version__", "")),
            "weather_numeric_fields": fields,
            "weather_preset_count": len(presets),
            "weather_presets": presets,
        }
    except Exception as exc:
        return {"available": False, "error": f"{type(exc).__name__}:{exc}"}


def write(path: Path, payload: Dict[str, Any]) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=True) + "\n",
        encoding="utf-8",
    )
    return str(path)


